/**
 * Writes public/yurui-env.js from VITE_* env (and .env / .env.local files).
 * English: Classic scripts cannot use import.meta.env after Hosting deploy;
 * this file is copied to dist/ and loaded before config.js.
 * 中文：正式靜態檔無法用 Vite 的 import.meta.env，故在 build／dev 前產出覆寫檔。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, '..');
const outFile = path.join(frontendRoot, 'public', 'yurui-env.js');

/**
 * Minimal .env parser (KEY=VALUE, ignores comments / blanks).
 * @param {string} filePath
 * @returns {Record<string, string>}
 */
function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  /** @type {Record<string, string>} */
  const map = {};
  const text = fs.readFileSync(filePath, 'utf8');
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) {
      continue;
    }
    const eq = line.indexOf('=');
    if (eq <= 0) {
      continue;
    }
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    map[key] = value;
  }
  return map;
}

const fromFiles = {
  ...loadEnvFile(path.join(frontendRoot, '.env')),
  ...loadEnvFile(path.join(frontendRoot, '.env.local')),
};

/**
 * Prefer process.env (CI / one-off `$env:VITE_...=`) over files.
 * @param {string} key
 * @returns {string}
 */
function readVite(key) {
  const fromProcess = process.env[key];
  if (fromProcess != null && String(fromProcess).trim() !== '') {
    return String(fromProcess).trim();
  }
  const fromFile = fromFiles[key];
  if (fromFile != null && String(fromFile).trim() !== '') {
    return String(fromFile).trim();
  }
  return '';
}

const apiBase = readVite('VITE_API_BASE_URL').replace(/\/+$/, '');
const lineOa = readVite('VITE_LINE_OA_CHAT_URL');

const payload = {
  API_BASE_URL: apiBase,
  LINE_OA_CHAT_URL: lineOa,
};

fs.mkdirSync(path.dirname(outFile), { recursive: true });
const body =
  '/* AUTO-GENERATED by scripts/write-yurui-env.mjs — do not edit */\n' +
  'window.__YURUI_ENV__ = ' +
  JSON.stringify(payload, null, 2) +
  ';\n';

fs.writeFileSync(outFile, body, 'utf8');
console.log(
  '[write-yurui-env] wrote',
  path.relative(frontendRoot, outFile),
  apiBase ? `(API_BASE_URL=${apiBase})` : '(API_BASE_URL=default from config.js)'
);
